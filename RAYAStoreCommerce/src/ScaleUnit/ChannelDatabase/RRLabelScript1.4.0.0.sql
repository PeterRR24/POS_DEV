  ISNULL(id.INVENTSIZEID, '') AS 'DIMSIZEID', ISNULL(id.INVENTCOLORID, '') AS 'DIMCOLORID', ISNULL(id.INVENTSTYLEID, '') AS 'DIMSTYLEID', ISNULL(id.CONFIGID, '') AS 'DIMCONFIGID',
  ISNULL(dvc.NAME, '') AS 'DIMCOLORNAME', ISNULL(dvsz.NAME, '') AS 'DIMSIZENAME', ISNULL(dvst.NAME, '') AS 'DIMSTYLENAME', ISNULL(dvcfg.NAME, '') AS 'DIMCONFIGNAME',
  ISNULL(uomt.DESCRIPTION, '') AS UNITNAME, ISNULL(uomtb.DESCRIPTION, '') AS BASEUNITNAME, ISNULL(uomte.DESCRIPTION, '') AS EQUIVUNITNAME,
  ISNULL(rse.DESCRIPTION, '') AS SEASONNAME, ISNULL(rss.NAME, '') AS SECTIONNAME, ISNULL(rssh.NAME, '') AS SHELFNAME,
  li.DATARECID, ld.TEXT, ld.TEXT2, ld.TEXT3, ld.NUMBER, ld.PERIOD,
