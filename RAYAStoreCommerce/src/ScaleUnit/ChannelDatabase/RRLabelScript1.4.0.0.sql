--- GETITEMVARIANTAVAILABILITY

CREATE FUNCTION [ext].[GETITEMVARIANTAVAILABILITY]
(
    @bi_ChannelId	BIGINT,
    @tvp_ids		[ext].RRITEMINVENTDIMTABLETYPE READONLY
)
RETURNS @result TABLE
(
	ITEMID NVARCHAR(20),
	VARIANTINVENTDIMID NVARCHAR(20),
	UNITID NVARCHAR(10),
	AVAILPHYSICAL NUMERIC(32, 16)
)
AS
BEGIN
	DECLARE @nvc_DataAreaId	NVARCHAR(4)
	DECLARE @nvc_LocationId	NVARCHAR(20)
	DECLARE @nvc_StoreId	NVARCHAR(20)
	DECLARE @i_MaxCounter	INT = 0

	SELECT @nvc_DataAreaId = RCT.INVENTLOCATIONDATAAREAID, @nvc_LocationId = RCT.INVENTLOCATION, @nvc_StoreId = RST.STORENUMBER
	  FROM [ax].RETAILCHANNELTABLE RCT INNER JOIN [ax].[RETAILSTORETABLE] RST ON RST.RECID = RCT.RECID
	  WHERE RCT.RECID = @bi_ChannelId;

	SELECT @i_MaxCounter = ICC.REPLICATIONCOUNTER
	  FROM [ext].[RUINVENTCHANNELCOUNTER] ICC
	  WHERE ICC.CHANNEL = @bi_ChannelId AND ICC.CREATEDOFFLINE = 0;

	INSERT INTO @result
	  SELECT ID.ITEMID, ID.INVENTDIMID, ITM.UNITID, (ISNULL(RIA.QTY,0) + ISNULL(RTS.QTY,0)) AS AVAILPHYSICAL FROM @tvp_ids ID
		LEFT JOIN [ax].INVENTTABLEMODULE ITM ON ITM.ITEMID = ID.ITEMID AND ITM.DATAAREAID = @nvc_DataAreaId AND ITM.MODULETYPE = 0
		LEFT JOIN [ext].GETRETAILINVENTAVAILABILITY(@nvc_DataAreaId,@nvc_LocationId,@tvp_ids) RIA ON RIA.ITEMID = ID.ITEMID AND RIA.INVENTDIMID = ID.INVENTDIMID
		LEFT JOIN [ext].GETRETAILINVENTSALESTRANS(@nvc_DataAreaId,@nvc_StoreId,@i_MaxCounter,@tvp_ids) RTS ON RTS.ITEMID = ID.ITEMID AND RTS.INVENTDIMID = ID.INVENTDIMID
	RETURN
END

GO
