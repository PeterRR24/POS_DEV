--- GETRETAILINVENTSALESTRANS

CREATE FUNCTION [ext].[GETRETAILINVENTSALESTRANS]
(
    @nvc_DataAreaId	NVARCHAR(4),
    @nvc_StoreId	NVARCHAR(20),
    @i_MaxCounter	INT,
    @tvp_ids		[ext].RRITEMINVENTDIMTABLETYPE READONLY
)
RETURNS TABLE
RETURN
	SELECT IV.ITEMID, IV.INVENTDIMID, SUM(RTS.QTY) AS QTY
	FROM @tvp_ids IV 
		INNER JOIN [ax].RETAILTRANSACTIONSALESTRANS RTS ON RTS.ITEMID = IV.ITEMID
        INNER JOIN [ax].RETAILTRANSACTIONTABLE RT ON 
   		   RTS.CHANNEL = RT.CHANNEL AND RTS.STORE = RT.STORE AND RTS.TERMINALID = RT.TERMINAL AND RTS.TRANSACTIONID = RT.TRANSACTIONID AND RTS.DATAAREAID = RT.DATAAREAID
	WHERE IV.INVENTDIMID = '' AND RTS.DATAAREAID = @nvc_DataAreaId AND RTS.STORE = @nvc_StoreId AND
		RT.TYPE = 2 AND RT.ENTRYSTATUS = 0 AND RTS.TRANSACTIONSTATUS = 0 AND RTS.REPLICATIONCOUNTERFROMORIGIN > @i_MaxCounter
	GROUP BY IV.ITEMID, IV.INVENTDIMID
	UNION ALL
	SELECT IV.ITEMID, IV.INVENTDIMID, SUM(RTS.QTY) AS QTY
	FROM @tvp_ids IV 
		INNER JOIN [ax].RETAILTRANSACTIONSALESTRANS RTS ON RTS.ITEMID = IV.ITEMID
        INNER JOIN [ax].RETAILTRANSACTIONTABLE RT ON 
   		   RTS.CHANNEL = RT.CHANNEL AND RTS.STORE = RT.STORE AND RTS.TERMINALID = RT.TERMINAL AND RTS.TRANSACTIONID = RT.TRANSACTIONID AND RTS.DATAAREAID = RT.DATAAREAID
		INNER JOIN [ax].INVENTDIMCOMBINATION IDC ON IDC.RETAILVARIANTID = RTS.VARIANTID AND IDC.DATAAREAID = RTS.DATAAREAID AND IDC.INVENTDIMID = IV.INVENTDIMID
	WHERE IV.INVENTDIMID <> '' AND RTS.DATAAREAID = @nvc_DataAreaId AND RTS.STORE = @nvc_StoreId AND 
		RT.TYPE = 2 AND RT.ENTRYSTATUS = 0 AND RTS.TRANSACTIONSTATUS = 0 AND RTS.REPLICATIONCOUNTERFROMORIGIN > @i_MaxCounter	
	GROUP BY IV.ITEMID, IV.INVENTDIMID

