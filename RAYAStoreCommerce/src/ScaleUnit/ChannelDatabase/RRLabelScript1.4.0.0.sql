CREATE FUNCTION [ext].[GETPRODUCTLABELPROFILEID]
(
    @bi_ProductId     BIGINT,
    @bi_HierarchyId   BIGINT
)
RETURNS BIGINT
AS
BEGIN
  DECLARE @ProfileId BIGINT;

  SELECT TOP 1 @ProfileId = LS.LABELPROFILERECID FROM ext.PRLABELSETUP LS WHERE LS.PRODUCTRECID = @bi_ProductId AND LS.HIERARCHYRECID = 0

  IF @ProfileId IS NULL
  BEGIN
    WITH LABELSETUPHIERARCHY(PARENTCATEGORY, CATEGORYHIERARCHY, [LEVEL]) AS
    ( 
      --anchor member definition 
      SELECT C.RECID, C.CATEGORYHIERARCHY, 0 AS [LEVEL] FROM ax.ECORESCATEGORY C
        INNER JOIN ax.ECORESPRODUCTCATEGORY PC ON C.RECID = PC.CATEGORY
      WHERE PC.PRODUCT = @bi_ProductId AND C.CATEGORYHIERARCHY= @bi_HierarchyId
      UNION ALL 
      --recursive member definition 
      SELECT C.PARENTCATEGORY, C.CATEGORYHIERARCHY, H.[LEVEL] + 1 FROM ax.ECORESCATEGORY C
        INNER JOIN LABELSETUPHIERARCHY H ON C.RECID = H.PARENTCATEGORY 
      WHERE C.PARENTCATEGORY <> 0
    )
    SELECT TOP 1 @ProfileId = LS.LABELPROFILERECID FROM LABELSETUPHIERARCHY H 
      INNER JOIN [ext].PRLABELSETUP LS ON H.CATEGORYHIERARCHY = LS.HIERARCHYRECID AND H.PARENTCATEGORY = LS.CATEGORYRECID
    ORDER BY [LEVEL]
  END

  RETURN ISNULL(@ProfileId, 0);
END

GO
